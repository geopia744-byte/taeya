# -*- coding: utf-8 -*-
"""컷 나누기 — 이 프로그램의 심장

대본을 12~13초짜리 토막으로 자른다.
토막 하나 = 그림 한 장 = 자막 한 구간.

영상 실측 기준
    대본 4,621자  →  9분(540초)  →  43컷
    1초에 약 8.55자  (= 1분에 513자)
    한 컷 ≈ 107자
"""

import re

초당글자 = 8.55          # 영상 실측: 4,621자 ÷ 540초
후킹초 = 8.0             # 첫 2분은 촘촘하게
기본초 = 13.0
후킹길이 = 72.0          # 영상 실측: 후킹 9장 x 8초 = 72초

# 문단(빈 줄)에서 끊으려면 목표 길이의 몇 할은 채워야 하는가.
# 0.85 면 13초 목표일 때 11.1초는 채워야 문단을 존중한다.
#
# 이 선이 없으면(옛 코드처럼 문단마다 무조건 끊으면)
# 클로드 대본은 한두 문장마다 빈 줄이 들어가는 탓에
# 컷이 3~6초로 토막 나고 목표 길이가 아무 뜻이 없어진다.
#
# 0.85 는 세 가지 대본 모양(짧은 문장·긴 문장·빈 줄 없음)으로
# 0.6부터 1.0까지 재어 보고 고른 값이다.
# 0.85 위로는 결과가 같다. 곧 목표를 해치지 않으면서
# 문단을 가장 많이 존중할 수 있는 지점이다.
문단존중선 = 0.85

구간색 = {'후킹': '#f59e0b', '본문': '#38bdf8', '강조': '#a78bfa', '마무리': '#34d399'}


def 문장나누기(대본):
    """대본을 문장 단위로 쪼갠다.

    온점·물음표·느낌표 뒤에 공백이나 줄바꿈이 오면 거기서 끊는다.
    (대본 작성 가이드 1번 「문장 끝 온점 후 반드시 띄어쓰기」가 이것 때문이다.)
    문단(빈 줄)은 반드시 끊는 자리로 본다.
    """
    문장 = []
    for 문단 in re.split(r'\n\s*\n', 대본.strip()):
        문단 = 문단.strip()
        if not 문단:
            continue
        조각 = re.split(r'(?<=[.!?])\s+', 문단.replace('\n', ' '))
        for s in 조각:
            s = s.strip()
            if s:
                문장.append({'글': s, '문단끝': False})
        if 문장:
            문장[-1]['문단끝'] = True
    return 문장


def 읽는시간(글, 실측=None):
    """이 글을 소리내어 읽는 데 걸리는 시간(초).

    실측이 있으면(음성을 이미 만들었으면) 그 값을 쓴다. 없으면 글자수로 어림잡는다.
    """
    if 실측 is not None:
        return float(실측)
    글자 = len(re.sub(r'\s', '', 글))
    return 글자 / 초당글자


강조장수 = 4      # 마무리 직전 몇 장을 강조로 볼지 (영상 실측: 16초에도 13초에도 4장)
마무리장수 = 2    # 마지막 몇 장을 마무리로 볼지


def 구간정하기(시작초, 전체초):
    """자르는 동안 쓰는 임시 구간. 후킹인지 아닌지만 본다."""
    return '후킹' if 시작초 < 후킹길이 else '본문'


def 구간매기기(컷목록, 후킹초수=None, 강조=강조장수, 마무리=마무리장수):
    """다 자른 뒤에 네 구간을 매긴다.

    영상 실측
        16초 설정 → 후킹 9장 + 본문 22장 + 강조 4장 + 마무리 1장 = 36장
        13초 설정 → 후킹 9장 + 본문 28장 + 강조 4장 + 마무리 2장 = 43장
    후킹은 앞쪽 일정 시간, 강조는 끝에서 마무리 바로 앞 몇 장으로 고정된다.
    """
    n = len(컷목록)
    if not n:
        return 컷목록
    한계 = 후킹길이 if 후킹초수 is None else 후킹초수
    마무리시작 = max(0, n - 마무리)
    강조시작 = max(0, 마무리시작 - 강조)
    for i, c in enumerate(컷목록):
        if c['시작초'] < 한계:
            c['구간'] = '후킹'
        elif i >= 마무리시작:
            c['구간'] = '마무리'
        elif i >= 강조시작:
            c['구간'] = '강조'
        else:
            c['구간'] = '본문'
    return 컷목록


def 컷나누기(대본, 목표초=기본초, 후킹목표=후킹초, 문장길이=None,
             강조목표=None, 마무리목표=None):
    """대본을 컷으로 자른다.

    원칙
      1. 문장 중간에서 자르지 않는다.
         (자르면 자막이 깨지고, 그림이 글과 안 맞는다)
      2. 문장을 차례로 모으다가 목표 시간을 넘기 직전/직후 중
         목표에 더 가까운 쪽에서 끊는다.
      3. 한 문장이 목표보다 길면 그 문장 혼자 한 컷이 된다.
      4. 문단이 끝나면 되도록 거기서 끊는다. (이야기 단위가 맞는다)
      5. 앞 2분(후킹)은 더 짧게 끊는다. 실측상 훅만은 컷 수가 조회수에 영향을 줬다.

    돌려주는 것: 컷 목록. 컷마다
        번호 / 대본 / 시작초 / 끝초 / 길이초 / 글자수 / 구간
    """
    문장 = 문장나누기(대본)
    if not 문장:
        return []

    for i, s in enumerate(문장):
        실측 = 문장길이[i] if (문장길이 and i < len(문장길이)) else None
        s['초'] = 읽는시간(s['글'], 실측)

    전체초 = sum(s['초'] for s in 문장)

    컷목록 = []
    담은것, 담은초, 시작초 = [], 0.0, 0.0

    def 끊기():
        nonlocal 담은것, 담은초, 시작초
        if not 담은것:
            return
        글 = ' '.join(s['글'] for s in 담은것)
        구간 = 구간정하기(시작초, 전체초)
        컷목록.append({
            '번호': len(컷목록) + 1,
            '대본': 글,
            '시작초': round(시작초, 2),
            '끝초': round(시작초 + 담은초, 2),
            '길이초': round(담은초, 2),
            '글자수': len(re.sub(r'\s', '', 글)),
            '구간': 구간,
        })
        시작초 += 담은초
        담은것, 담은초 = [], 0.0

    def 문단에서끊을까(담은초, 목표):
        """문단(빈 줄)이 끝났다. 여기서 끊는 게 나은가?

        문단 경계에서 끊으면 이야기 단위가 맞아서 보기 좋다.
        하지만 그건 있으면 좋은 것이지 반드시 지킬 것은 아니다.

        클로드가 쓴 대본은 한두 문장마다 빈 줄이 들어간다.
        그래서 문단마다 무조건 끊으면 13초를 채우기도 전에 잘려서
        3~6초짜리 토막이 쏟아진다. 목표 길이가 무의미해지고
        그림도 두 배로 들어간다. (실제로 그렇게 나왔다)

        그래서 목표의 일정 비율은 채웠을 때만 문단을 존중한다.
        """
        return 담은초 >= 목표 * 문단존중선

    def 담기(s, 목표):
        nonlocal 담은초
        담은것.append(s)
        담은초 += s['초']
        if 담은초 >= 목표 or (s['문단끝'] and 문단에서끊을까(담은초, 목표)):
            끊기()

    for s in 문장:
        이번목표 = 후킹목표 if 시작초 < 후킹길이 else 목표초

        # 아직 아무것도 안 담았으면 일단 담는다 (문장 중간은 못 자르므로)
        if not 담은것:
            담기(s, 이번목표)
            continue

        # 이 문장을 더 담으면 목표에서 더 멀어지나?
        지금차이 = abs(담은초 - 이번목표)
        더한차이 = abs(담은초 + s['초'] - 이번목표)

        if 더한차이 > 지금차이:
            끊기()
        담기(s, 이번목표)

    끊기()
    return 구간매기기(컷목록, 후킹길이, 강조장수, 마무리장수)


def 요약(컷목록):
    if not 컷목록:
        return {}
    전체 = 컷목록[-1]['끝초']
    구간수 = {}
    for c in 컷목록:
        구간수[c['구간']] = 구간수.get(c['구간'], 0) + 1
    return {
        '컷수': len(컷목록),
        '전체초': round(전체, 1),
        '전체분': round(전체 / 60, 1),
        '평균컷초': round(전체 / len(컷목록), 1),
        '구간별': 구간수,
        '글자수': sum(c['글자수'] for c in 컷목록),
    }


CTA말 = ['구독', '좋아요', '알림 설정', '댓글', '하이프', '채널 추가']


def CTA인가(글):
    """「구독과 좋아요 눌러주세요」 같은 부탁 문단인가.

    레퍼런스 영상은 이런 문단에 그림을 붙이지 않았다.
    (장면 1~6 중 구독 문단만 건너뛰었다)
    """
    짧다 = len(re.sub(r'\s', '', 글)) < 140
    걸린말 = sum(1 for w in CTA말 if w in 글)
    return 짧다 and 걸린말 >= 2


def CTA빼기(컷목록):
    """구독 부탁 문단에는 그림을 따로 만들지 않는다.

    그렇다고 그 시간에 화면이 비면 안 되므로, 그 시간만큼 **앞 컷을 늘린다.**
    (앞 그림이 그대로 이어져 보인다.)
    맨 앞이면 뒤 컷을 앞으로 당긴다.
    """
    남김 = []
    for c in 컷목록:
        if CTA인가(c['대본']):
            c['CTA'] = True
            if 남김:
                앞 = 남김[-1]
                앞['끝초'] = c['끝초']
                앞['길이초'] = round(앞['끝초'] - 앞['시작초'], 2)
                앞['이어붙인CTA'] = c['대본']
                continue
            # 맨 앞이면 뒤 컷이 이어받도록 표시만 남긴다
            남김.append(c)
            continue
        if 남김 and 남김[-1].get('CTA'):
            앞 = 남김.pop()
            c['시작초'] = 앞['시작초']
            c['길이초'] = round(c['끝초'] - c['시작초'], 2)
            c['이어붙인CTA'] = 앞['대본']
        남김.append(c)

    for i, c in enumerate(남김):
        c['번호'] = i + 1
        c.pop('CTA', None)
    return 구간매기기(남김)


def 프롬프트만들기(컷, 화풍='', 캐릭터=''):
    """컷 하나를 그림 프롬프트로 바꿀 때 쓰는 틀.

    여기서는 「무엇을 넣어야 하는가」만 정해 둔다.
    실제 영문 묘사를 쓰는 일은 4차에서 클로드가 한다.
    """
    return {
        '컷번호': 컷['번호'],
        '대본': 컷['대본'],
        '길이초': 컷['길이초'],
        '구간': 컷['구간'],
        '화풍': 화풍,
        '캐릭터': 캐릭터,
        '장면묘사': '',   # 한국어. 4차에서 채움
        '영문프롬프트': '',  # 화풍·캐릭터가 얹힌 최종 프롬프트. 4차에서 채움
    }


if __name__ == '__main__':
    import sys, json
    글 = sys.stdin.read()
    목표 = float(sys.argv[1]) if len(sys.argv) > 1 else 기본초
    컷 = 컷나누기(글, 목표)
    print(json.dumps({'요약': 요약(컷), '컷': 컷}, ensure_ascii=False, indent=2))
